-- 002_builder: API Builder (proyectos, inventario de tablas y endpoints)
-- Requiere 001_init.sql (tabla users). Esquema: public.

CREATE TABLE builder_projects (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               varchar(80)  NOT NULL,
    engine             varchar(20)  NOT NULL DEFAULT 'postgresql',
    host               varchar(255) NOT NULL,
    port               integer      NOT NULL DEFAULT 5432,
    database_name      varchar(128) NOT NULL,
    username           varchar(128) NOT NULL,
    encrypted_password text         NOT NULL,   -- cifrada con ENCRYPTION_KEY; nunca se devuelve por la API
    ssl_mode           varchar(20)  NOT NULL DEFAULT 'prefer',
    created_by         integer REFERENCES users (id) ON DELETE SET NULL,
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_builder_projects_engine   CHECK (engine IN ('postgresql')),
    CONSTRAINT ck_builder_projects_ssl_mode CHECK (ssl_mode IN ('disable', 'prefer', 'require')),
    CONSTRAINT ck_builder_projects_port     CHECK (port BETWEEN 1 AND 65535)
);

CREATE UNIQUE INDEX uq_builder_projects_name ON builder_projects (lower(name));

CREATE TRIGGER trg_builder_projects_updated_at
    BEFORE UPDATE ON builder_projects
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE builder_resources (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   integer      NOT NULL REFERENCES builder_projects (id) ON DELETE CASCADE,
    schema_name  varchar(128) NOT NULL,
    table_name   varchar(128) NOT NULL,
    primary_key  jsonb        NOT NULL DEFAULT '[]'::jsonb,
    is_sensitive boolean      NOT NULL DEFAULT false,
    status       varchar(20)  NOT NULL DEFAULT 'NOT_GENERATED',
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_builder_resources_table UNIQUE (project_id, schema_name, table_name),
    CONSTRAINT ck_builder_resources_status CHECK (status IN ('NOT_GENERATED', 'PUBLISHED', 'DISABLED', 'ERROR'))
);

CREATE INDEX ix_builder_resources_project_id ON builder_resources (project_id);

CREATE TRIGGER trg_builder_resources_updated_at
    BEFORE UPDATE ON builder_resources
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE builder_resource_endpoints (
    resource_id integer     NOT NULL REFERENCES builder_resources (id) ON DELETE CASCADE,
    method      varchar(10) NOT NULL,
    selected    boolean     NOT NULL DEFAULT true,   -- elegido por el usuario
    generated   boolean     NOT NULL DEFAULT false,  -- ya generado por el motor (fase 2)
    PRIMARY KEY (resource_id, method),
    CONSTRAINT ck_builder_endpoints_method CHECK (method IN ('GET', 'POST', 'PUT', 'DELETE'))
);
